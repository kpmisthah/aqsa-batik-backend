async function seed() {
    try {
        await client.connect();
        const db = client.db('batik_store');
        const blogsCollection = db.collection('blogs');

        for (const blog of blogList) {
            const fullContent = BLOG_POSTS[blog.slug];
            const newDoc = {
                title: blog.title,
                slug: blog.slug,
                excerpt: blog.excerpt,
                content: fullContent.content,
                featuredImg: blog.image,
                published: true,
                author: fullContent.author || 'Aqsha Editorial',
                metaTitle: fullContent.seoTitle || blog.title,
                metaDesc: fullContent.seoDescription || blog.excerpt,
                category: blog.category,
                createdAt: new Date(new Date().getTime() - Math.random() * 10000000), // Random recent date
                updatedAt: new Date()
            };
            
            // Upsert based on slug so we don't duplicate on multiple runs
            await blogsCollection.updateOne(
                { slug: newDoc.slug },
                { $set: newDoc },
                { upsert: true }
            );
            console.log("Seeded:", newDoc.slug);
        }
        console.log("Done seeding blogs.");
    } catch (e) {
        console.error(e);
    } finally {
        await client.close();
    }
}

